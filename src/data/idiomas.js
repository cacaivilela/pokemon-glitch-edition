// O jogo foi escrito em português: os diálogos, os nomes de item, as telas.
// Traduzir isso "de verdade" seria trocar as chaves de todo texto do jogo por
// códigos — e aí o arquivo de história, que hoje se lê como um roteiro, viraria
// uma lista de identificadores.
//
// Então a tradução é por FRASE: cada idioma é um dicionário do texto em
// português pro texto no outro idioma, e a troca acontece na hora de DESENHAR
// (`drawText`, em src/core/font.js) e na hora de quebrar a linha da caixa de
// diálogo (src/systems/dialogue.js). Duas consequências boas:
//
//   1. nenhum arquivo de dados precisa saber que existe tradução;
//   2. o que não estiver traduzido aparece em português, e o jogo continua
//      inteiro em vez de mostrar buraco.
//
// Tudo é comparado em MAIÚSCULA, porque a fonte do jogo é maiúscula.
// Escrever tradução nova aqui vale na hora: isto é src/data/, tem hot-swap.

