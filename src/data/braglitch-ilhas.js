// BRAGLITCH — AS ILHAS: a história de lá (formato dos lugares em dev/LUGARES.md).
//
// A PROFA. IPÊ tem uma teoria: toda FORMA BRAGLITCHIANA nasceu numa ilha. O
// mesmo bicho de sempre chegou num pedaço de terra cercado de mar, ficou
// sozinho lá por gerações e foi virando outra coisa — como um save copiado
// que cada cópia continua jogando do seu jeito. As OITO ILHAS da costa são
// onde as formas começaram, 14 em cada uma, e é lá que elas vivem (no
// continente não tem -BRAG no mato: quem aparece por lá é de treinador).
//
// Os oito GINÁSIOS ficam no continente (src/data/braglitch-mundo.js), e cada
// ilha tem O SEU CHEFE: uma forma -BRAG evoluída, grande e brava, que manda na ilha
// (`chefe`). Ele espera parado; falar com ele é a luta, e dá pra capturar.
//
// Quem leva é a IPÊ, na lancha dela, saindo do píer de SÃO LUCARIO DO SUL. Uma
// ilha só abre depois da anterior. Ilha COMPLETA é ilha com o chefe vencido ou
// capturado; as 14 formas são pra descobrir (a IPÊ conta quantas você tem, mas
// elas não trancam a próxima ilha). Nas cinco primeiras, a IPÊ acha um PANDEIRO DA TERRA
// (src/data/braglitch.js, PANDEIROS).
//
// O PROF. CARVALHO atravessa o mar depois da primeira ilha e fica na lancha
// com ela: a cada ilha completa ele compara as formas com os primos de Kanto.
//
// `formas`: as 14 (as fichas de cada uma estão em braglitch-formas-ilha<N>.js,
// os desenhos em tools/braglitch_desenhos/lote_20..27.py). `lancha`: onde a
// IPÊ fica (e o CARVALHO, em `carvalho`); `chegada`: onde a lancha te deixa.

